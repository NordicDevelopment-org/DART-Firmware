#!/usr/bin/env python3
"""Generate the NDI 1 W Meshtastic variant files from pin_table.csv.

pin_table.csv is the single source of truth for pin numbers. check_netlist.py checks it
against the hardware netlist. Nothing in the generated files is typed by hand.

Outputs (default directory: ndi_1w/meshtastic/overlay/variants/nrf52840/ndi_1w):
  variant.h              pin macros + Arduino variant boilerplate (from templates/variant.h.in)
  ndi_pin_init.inc       boot-state table used by variant.cpp initVariant()
  ndi_forbidden_guard.h  #error guards from meshtastic/forbidden_macros.txt
and, with the default --md path, ndi_1w/docs/PINMAP.md (human-readable table).

Usage:
  python3 -I gen_variant.py            write the generated files
  python3 -I gen_variant.py --check    exit 1 if the files on disk differ from the generated text
"""
import argparse
import csv
import difflib
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)  # ndi_1w/
DEFAULT_TABLE = os.path.join(HERE, "pin_table.csv")
DEFAULT_TEMPLATE = os.path.join(HERE, "templates", "variant.h.in")
DEFAULT_OUT = os.path.join(ROOT, "meshtastic", "overlay", "variants", "nrf52840", "ndi_1w")
DEFAULT_FORBIDDEN = os.path.join(ROOT, "meshtastic", "forbidden_macros.txt")
DEFAULT_MD = os.path.join(ROOT, "docs", "PINMAP.md")

# Boot states the table may ask for. Only the first four are applied by initVariant().
APPLIED_MODES = ("INPUT", "INPUT_PULLUP", "OUTPUT_HIGH", "OUTPUT_LOW")
OTHER_MODES = ("ANALOG", "PERIPHERAL", "RESERVED", "NC")
INIT_MODES = APPLIED_MODES + OTHER_MODES

# Stock Meshtastic / Arduino macro names this generator knows how to place. A typo in the
# table fails here instead of silently producing a macro nothing reads.
STOCK_MACROS = (
    "PIN_LED1", "PIN_BUTTON1", "PIN_A0", "PIN_WIRE_SDA", "PIN_WIRE_SCL",
    "PIN_SERIAL1_RX", "PIN_SERIAL1_TX", "PIN_GPS_PPS", "PIN_GPS_EN",
    "SX126X_POWER_EN", "SX126X_RESET", "SX126X_CS", "SX126X_BUSY", "SX126X_DIO1",
    "PIN_SPI_SCK", "PIN_SPI_MOSI", "PIN_SPI_MISO",
)
# alias -> primary macro it must sit on. 'SS' is a const in the Arduino core, not a macro.
ALLOWED_ALIASES = {
    "BATTERY_PIN": "PIN_A0",
    "GPS_RX_PIN": "PIN_SERIAL1_RX",
    "GPS_TX_PIN": "PIN_SERIAL1_TX",
    "LED_GREEN": "PIN_LED1",
    "SS": "SX126X_CS",
}
CONST_ALIASES = ("SS",)
# Arduino analog names A1..A5 follow the NDI tap macros (A0 is the stock battery tap).
ANALOG_NAMES = {
    "PIN_A1": "NDI_PIN_VS_USB",
    "PIN_A2": "NDI_PIN_BT_TEMP",
    "PIN_A3": "NDI_PIN_VS_AUX",
    "PIN_A4": "NDI_PIN_VLOGIC_HALF",
    "PIN_A5": "NDI_PIN_CHEM_ID",
}
IDENT = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*$")


def ascii_clean(text):
    """Table text goes into C comments: ASCII only, and no em or en dashes."""
    # Characters are built from code points so this file itself stays plain ASCII.
    swaps = {0x2014: "-", 0x2013: "-", 0x00B5: "u", 0x03A9: "ohm", 0x00B1: "+/-"}
    for code, repl in swaps.items():
        text = (text or "").replace(chr(code), repl)
    return (text or "").encode("ascii", "replace").decode("ascii")


def load_forbidden(path):
    """name -> reason, from forbidden_macros.txt ('NAME  # reason' per line)."""
    out = {}
    with open(path, encoding="utf-8") as f:
        for line in f:
            body, _, reason = line.partition("#")
            body = body.strip()
            if body:
                out[body.split()[0]] = ascii_clean(reason).strip().replace('"', "'")
    return out


def render_guard(forbidden):
    out = [
        "// GENERATED by ndi_1w/pin_table/gen_variant.py from ndi_1w/meshtastic/forbidden_macros.txt. DO NOT EDIT BY HAND.",
        "// Included first by ndi_config.h. A forbidden macro defined by a build flag or an earlier header stops the build.",
    ]
    for name, reason in forbidden.items():
        out += [f"#ifdef {name}", f'#error "NDI 1 W: {name} must not be defined ({reason})"', "#endif"]
    return "\n".join(out) + "\n"


def load_table(path):
    """Read the table. The table writes '-' for 'none' in the macro columns; treat it as empty."""
    with open(path, encoding="utf-8", newline="") as f:
        rows = list(csv.DictReader(f))
    for r in rows:
        for col in ("variant_macro", "variant_macro_aliases"):
            if r[col].strip() == "-":
                r[col] = ""
        if r["macro_kind"].strip() in ("", "-"):
            r["macro_kind"] = "none"
    return rows


def expected_gpio_names():
    return [f"P0.{n:02d}" for n in range(32)] + [f"P1.{n:02d}" for n in range(16)]


def validate(rows, forbidden):
    errs = []
    names = [r["port_pin"].strip() for r in rows]
    if names != expected_gpio_names():
        errs.append("port_pin column must list P0.00..P0.31 then P1.00..P1.15 exactly once, in order")
    macros = {}
    for r in rows:
        pin = r["port_pin"].strip()
        m = re.fullmatch(r"P([01])\.(\d\d)", pin)
        if not m:
            errs.append(f"{pin}: bad port_pin")
            continue
        want = int(m.group(1)) * 32 + int(m.group(2))
        if str(r["arduino_number"]).strip() != str(want):
            errs.append(f"{pin}: arduino_number {r['arduino_number']!r} != {want}")
        if r["init_mode"].strip() not in INIT_MODES:
            errs.append(f"{pin}: init_mode {r['init_mode']!r} not in {INIT_MODES}")
        mac = r["variant_macro"].strip()
        kind = r["macro_kind"].strip()
        if mac:
            if not IDENT.match(mac):
                errs.append(f"{pin}: macro {mac!r} is not a C identifier")
            if mac in macros:
                errs.append(f"{pin}: macro {mac} already used by {macros[mac]}")
            macros[mac] = pin
            if mac in forbidden:
                errs.append(f"{pin}: macro {mac} is forbidden (forbidden_macros.txt)")
            if kind == "stock" and mac not in STOCK_MACROS:
                errs.append(f"{pin}: stock macro {mac} is not one this generator knows")
            if kind == "ndi" and not mac.startswith("NDI_PIN_"):
                errs.append(f"{pin}: NDI macro {mac} must start with NDI_PIN_")
            if kind not in ("stock", "ndi"):
                errs.append(f"{pin}: macro {mac} needs macro_kind stock or ndi, got {kind!r}")
        elif kind not in ("none", ""):
            errs.append(f"{pin}: no macro but macro_kind {kind!r}")
        for al in [a.strip() for a in r["variant_macro_aliases"].split(",") if a.strip()]:
            if al not in ALLOWED_ALIASES:
                errs.append(f"{pin}: alias {al} not allowed")
            elif ALLOWED_ALIASES[al] != mac:
                errs.append(f"{pin}: alias {al} must sit on {ALLOWED_ALIASES[al]}, not {mac!r}")
            if al in forbidden:
                errs.append(f"{pin}: alias {al} is forbidden")
            if al in macros:
                errs.append(f"{pin}: alias {al} duplicates a macro")
            macros[al] = pin
    for need in STOCK_MACROS:
        if need not in macros:
            errs.append(f"missing required stock macro {need}")
    for al in ALLOWED_ALIASES:
        if al not in macros:
            errs.append(f"missing required alias {al}")
    for tgt in ANALOG_NAMES.values():
        if tgt not in macros:
            errs.append(f"analog name needs macro {tgt}")
    return errs


def short(text, n):
    """Cut at a word boundary and say so, so a table cell never ends mid-word."""
    text = text.strip()
    if len(text) <= n:
        return text
    cut = text[: n - 3].rsplit(" ", 1)[0]
    return cut.rstrip(",;:( ") + "..."


def role_text(r):
    return short(ascii_clean(r["role"]), 64)


def pin_macros_block(rows):
    lines = []

    def emit(kind_filter, title):
        lines.append(f"/* ---- {title} ---- */")
        for r in rows:
            mac = r["variant_macro"].strip()
            if not mac or r["macro_kind"].strip() != kind_filter:
                continue
            n = int(r["arduino_number"])
            note = f"{r['port_pin'].strip()} {ascii_clean(r['net']).strip()}: {role_text(r)}"
            lines.append(f"#define {mac} ({n}) // {note}")
            for al in [a.strip() for a in r["variant_macro_aliases"].split(",") if a.strip()]:
                if al in CONST_ALIASES:
                    continue
                lines.append(f"#define {al} {mac}")
        lines.append("")

    emit("stock", "Stock Meshtastic and Arduino names (pin numbers from pin_table.csv)")
    emit("ndi", "NDI names (nets only NDI code uses; stock code must never touch these)")
    return "\n".join(lines).rstrip("\n")


def analog_block():
    return "\n".join(f"#define {name} ({target})" for name, target in ANALOG_NAMES.items())


def spi_block(rows):
    ss = [a for r in rows for a in [x.strip() for x in r["variant_macro_aliases"].split(",")] if a == "SS"]
    assert ss, "SS alias missing"
    return "\n".join([
        "static const uint8_t SS = SX126X_CS;",
        "static const uint8_t MOSI = PIN_SPI_MOSI;",
        "static const uint8_t MISO = PIN_SPI_MISO;",
        "static const uint8_t SCK = PIN_SPI_SCK;",
    ])


def render_variant_h(rows, template_path):
    with open(template_path, encoding="utf-8") as f:
        text = f.read()
    text = text.replace("@@PIN_MACROS@@", pin_macros_block(rows))
    text = text.replace("@@ANALOG_NAMES@@", analog_block())
    text = text.replace("@@SPI_CONSTS@@", spi_block(rows))
    if "@@" in text:
        raise SystemExit("unreplaced @@ token left in template")
    return text


def render_pin_init(rows):
    out = [
        "// GENERATED by ndi_1w/pin_table/gen_variant.py from pin_table.csv. DO NOT EDIT BY HAND.",
        "// One row per GPIO whose boot state initVariant() applies: (arduino pin, mode, port pin, net).",
        "// PERIPHERAL, ANALOG, RESERVED and NC pins are left alone (stock drivers or the reset state own them).",
    ]
    for r in rows:
        mode = r["init_mode"].strip()
        if mode in APPLIED_MODES:
            out.append(f'NDI_PIN_INIT_ROW({int(r["arduino_number"])}, NDI_INIT_{mode}, "{r["port_pin"].strip()}", "{ascii_clean(r["net"]).strip()}")')
    return "\n".join(out) + "\n"


def render_md(rows):
    out = [
        "# NDI 1 W Rev A0: nRF52840 pin map",
        "",
        "GENERATED by `ndi_1w/pin_table/gen_variant.py` from `pin_table.csv`. Do not edit by hand.",
        "Arduino number = 32 x port + pin. Boot = state `initVariant()` applies. Netlist: `ndi_1w/hardware/NDI_1W_RevA0.net`.",
        "",
        "| Pin | Ard | Net | Dir | Boot | Macro | Role | Safety |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for r in rows:
        mac = r["variant_macro"].strip() or "-"
        al = r["variant_macro_aliases"].strip()
        if al:
            mac += " (" + al + ")"
        safety = ascii_clean(r["safety"]).strip() or "-"
        out.append("| {} | {} | {} | {} | {} | {} | {} | {} |".format(
            r["port_pin"].strip(), r["arduino_number"].strip(), ascii_clean(r["net"]).strip()[:22],
            r["direction"].strip(), r["init_mode"].strip(), mac, role_text(r).replace("|", "/"),
            short(safety, 70).replace("|", "/")))
    return "\n".join(out) + "\n"


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--table", default=DEFAULT_TABLE)
    ap.add_argument("--template", default=DEFAULT_TEMPLATE)
    ap.add_argument("--out-dir", default=DEFAULT_OUT)
    ap.add_argument("--forbidden", default=DEFAULT_FORBIDDEN)
    ap.add_argument("--md", default=DEFAULT_MD, help="PINMAP.md path ('' to skip)")
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args(argv)

    rows = load_table(a.table)
    forbidden = load_forbidden(a.forbidden)
    errs = validate(rows, forbidden)
    if errs:
        print("pin_table.csv validation FAILED:", file=sys.stderr)
        for e in errs:
            print("  - " + e, file=sys.stderr)
        return 2

    outputs = {
        os.path.join(a.out_dir, "variant.h"): render_variant_h(rows, a.template),
        os.path.join(a.out_dir, "ndi_pin_init.inc"): render_pin_init(rows),
        os.path.join(a.out_dir, "ndi_forbidden_guard.h"): render_guard(forbidden),
    }
    if a.md:
        outputs[a.md] = render_md(rows)

    bad = 0
    for path, text in outputs.items():
        if a.check:
            have = ""
            if os.path.exists(path):
                with open(path, encoding="utf-8", newline="") as f:
                    have = f.read()
            if have != text:
                bad += 1
                print(f"OUT OF DATE: {path}", file=sys.stderr)
                diff = difflib.unified_diff(have.splitlines(), text.splitlines(), "on disk", "generated", lineterm="", n=1)
                for i, line in enumerate(diff):
                    if i > 40:
                        print("  ...", file=sys.stderr)
                        break
                    print("  " + line, file=sys.stderr)
        else:
            os.makedirs(os.path.dirname(path), exist_ok=True)
            with open(path, "w", encoding="utf-8", newline="\n") as f:
                f.write(text)
            print("wrote", path)
    if a.check:
        if bad:
            print("run: python3 -I ndi_1w/pin_table/gen_variant.py", file=sys.stderr)
            return 1
        print(f"generated files are up to date ({len(outputs)} files, {len(rows)} pins)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
